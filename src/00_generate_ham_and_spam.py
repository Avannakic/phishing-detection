def get_llama_response(prompt: str) -> str:
    try:
        response = ollama.generate(
            model=MODEL_NAME,
            prompt=prompt,
            stream=False,
            options={"temperature": TEMPERATURE}
        )
        return response["response"]
    except Exception as e:
        print(f"[Ошибка Ollama]: {e}")
        return ""


